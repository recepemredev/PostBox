        DB::statement(
            'CREATE INDEX messages_tenant_application_created_at_index '.
            'ON messages (tenant_id, application_id, created_at)'
        );

        RowLevelSecurity::protect('messages');

        // The current month and a two-month runway, so the table can accept a
        // write the moment it exists. Keeping the horizon topped up from here is
        // the scheduled command's job, not this migration's.
        MonthlyPartitions::ensure('messages', CarbonImmutable::now(), 2);
    }

    public function down(): void
    {
        // Dropping a partitioned table drops every partition beneath it — the
        // indexes, the policy and the CHECK all go with it in one statement.
        Schema::dropIfExists('messages');
    }
